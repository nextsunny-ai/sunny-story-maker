/** 매체 letter로 출력 양식 가이드 텍스트 가져오기. 없으면 fallback. */
export function getMediumFormatGuide(letter: string): string {
  const f = MEDIUM_FORMATS[letter];
  if (!f) {
    return `### 출력 양식\n매체에 맞는 한국 실무 표준 양식으로 출력.`;
  }
  return `${f.guide}\n\n#### 양식 예시 (이 매체 한국 작가 표준 — 그대로 따라)\n\`\`\`\n${f.example}\n\`\`\``;
}
